create table public.season (
  year integer primary key check (year between 1920 and 9999),
  active boolean not null default true,
  is_current boolean not null default false,
  check (not is_current or active)
);
create unique index season_one_current on public.season (is_current) where is_current;
create table public.week (
  year integer not null references public.season,
  week integer not null check (week between 1 and 22),
  published boolean not null default false,
  is_current boolean not null default false,
  primary key (year, week),
  check (not is_current or published)
);
create unique index week_one_current_per_season on public.week (year) where is_current;

create table public.game (
  game_id bigint generated by default as identity primary key check (game_id > 0),
  year integer not null,
  week integer not null,
  away_team_id smallint not null references public.team check (away_team_id between 1 and 32),
  home_team_id smallint not null references public.team check (home_team_id between 1 and 32),
  win_team_id smallint not null default 34 references public.team,
  game_date_time timestamptz,
  foreign key (year, week) references public.week,
  check (away_team_id <> home_team_id),
  check (win_team_id in (33, 34) or win_team_id in (away_team_id, home_team_id)),
  unique (year, week, away_team_id, home_team_id)
);
create table public.pick (
  pick_id bigint generated by default as identity primary key check (pick_id > 0),
  entry_id bigint not null references public.entry,
  game_id bigint not null references public.game,
  team_id smallint not null references public.team check (team_id between 1 and 32),
  updated_at timestamptz not null default now(),
  unique (entry_id, game_id)
);
create index pick_game_idx on public.pick (game_id);
create index pick_team_idx on public.pick (team_id);
create index game_away_idx on public.game (away_team_id);
create index game_home_idx on public.game (home_team_id);
create index game_winner_idx on public.game (win_team_id);

