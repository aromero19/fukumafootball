-- Historical IDs remain explicit/importable. No family accounts are required.
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on functions from anon, authenticated, service_role;
-- PostgreSQL grants function EXECUTE to PUBLIC globally, independently of schema defaults.
alter default privileges for role postgres revoke execute on functions from public;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.entry (
  entry_id bigint generated by default as identity primary key check (entry_id > 0),
  name_first text not null check (btrim(name_first) <> ''),
  name_last text not null default '',
  active boolean not null default true
);
create table private.entry_contact (
  entry_id bigint primary key references public.entry on delete cascade,
  email text not null check (email = btrim(email) and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
);
create table public.team (
  team_id smallint primary key check (team_id between 1 and 34),
  team_name text not null unique
);
