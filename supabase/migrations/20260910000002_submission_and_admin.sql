create table public.theme (
  theme_id bigint generated by default as identity primary key,
  theme_name text not null unique check (btrim(theme_name) <> ''),
  description text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0,
  is_default boolean not null default false,
  check (not is_default or active)
);
create unique index theme_one_default on public.theme (is_default) where is_default;
insert into public.theme (theme_name, is_default) values ('Default', true);
