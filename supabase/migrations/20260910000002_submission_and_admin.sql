  team_theme_image_id bigint generated by default as identity primary key,
  team_id smallint not null references public.team check (team_id between 1 and 32),
  theme_id bigint not null references public.theme,
  image_url text not null check (image_url ~ '^https://'),
  thumbnail_url text check (thumbnail_url ~ '^https://'),
  active boolean not null default true,
  sort_order integer not null default 0,
  unique (team_id, theme_id)
);
create index team_theme_image_theme_idx on public.team_theme_image (theme_id);
create table public.weekly_submission (
  entry_id bigint not null references public.entry,
  year integer not null,
  week integer not null,
  theme_id bigint not null references public.theme,
  submitted_at timestamptz not null default now(),
  revision integer not null default 1 check (revision > 0),
  primary key (entry_id, year, week),
  foreign key (year, week) references public.week
);
create index weekly_submission_latest_idx on public.weekly_submission (entry_id, submitted_at desc);
create index weekly_submission_week_idx on public.weekly_submission (year, week);
create index weekly_submission_theme_idx on public.weekly_submission (theme_id);

create table private.admin_user (
  user_id uuid primary key references auth.users on delete cascade
);
create function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from private.admin_user where user_id = auth.uid());
$$;
revoke all on function private.is_admin() from public;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;

